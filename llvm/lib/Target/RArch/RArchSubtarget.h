#ifndef __LLVM_LIB_TARGET_RArch_RArchSUBTARGET_H__
#define __LLVM_LIB_TARGET_RArch_RArchSUBTARGET_H__

#include "MCTargetDesc/RArchInfo.h"
#include "RArchRegisterInfo.h"
#include "RArchFrameLowering.h"
#include "RArchISelLowering.h"
#include "RArchInstrsInfo.h"
#include "llvm/CodeGen/SelectionDAGTargetInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include <string>

#define GET_SUBTARGETINFO_HEADER
#include "RArchGenSubtargetInfo.inc"

namespace llvm {

class TargetMachine;

class RArchSubtarget : public RArchGenSubtargetInfo {
  virtual void anchor();

  RArchRegisterInfo RegInfo;
  RArchInstrInfo InstrInfo;
  RArchFrameLowering FrameLowering;
  RArchTargetLowering TLInfo;
  SelectionDAGTargetInfo TSInfo;
  rarchABI::ABI TargetABI = rarchABI::ABI_LP64;
  MVT XLenVT = MVT::i64;
  unsigned XLen = 64;

public:
  RArchSubtarget(const Triple &TT, const std::string &CPU, const std::string &FS,
                  const TargetMachine &TM);

  /// Definition of function is auto generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  const RArchInstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const RArchFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const RArchTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const RArchRegisterInfo *getRegisterInfo() const override { return &RegInfo; }
  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }

  auto getTargetABI() const { return TargetABI; }
  auto getXLenVT() const { return XLenVT; }
  auto getXLen() const { return XLen; }
};

} // end namespace llvm

#endif // __LLVM_LIB_TARGET_RArch_RArchSUBTARGET_H__
